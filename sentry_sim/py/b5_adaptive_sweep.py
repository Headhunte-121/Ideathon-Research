"""B5 (round 2): adaptive 'chest still' threshold as an RTL VARIANT (baseline rtl/, model/, tb/ untouched).
   Generates rtl_variants/pod_node_adaptive.sv, rtl_variants/sentry_device_top_adaptive.sv, rtl_variants/tb_system_end_to_end_adaptive.sv
   from the baseline files by text substitution, then sweeps accelerometer noise (-DACCN equivalent) for baseline and variant.
Variant rule:  chest_still = scg_energy < max(SCG_THR, ADAPT_KN/8 x floor);  floor = running 10th percentile of the per-second chest energy,
   tracked with an up-step of ADAPT_UP and a down-step of ADAPT_DOWN (units: 1/16 code per second), updated ONLY while the wrist pulse is present
   (so it freezes at its pre-arrest value when the pulse is lost).  k = ADAPT_KN/8 is chosen on the model sweep.
   python py/b5_adaptive_sweep.py gen            (writes the variant files)
   python py/b5_adaptive_sweep.py sweep KN ...   (needs settings64.bat; runs scenarios S1, S3, S5 at ACCN 350/500/650/800/1000 for the baseline and for each KN)
   python py/b5_adaptive_sweep.py full KN ACCN   (all 11 scenarios, 35 checks, baseline and variant)
Output: results/b5_sweep.csv, results/b5_full.csv, results/b5_log.txt"""
import csv, os, re, subprocess, sys

V = "rtl_variants"; WORK = "xsim_work_b5"; NOISES = (350, 500, 650, 800, 1000)


def gen():
    os.makedirs(V, exist_ok=True)
    p = open("rtl/pod_node.sv", encoding="utf-8").read()
    p = p.replace("module pod_node #(", "module pod_node_adaptive #(", 1)
    a = "REARM_S = 60, DISP_RETRY_S = 2\n)("
    assert a in p; p = p.replace(a, "REARM_S = 60, DISP_RETRY_S = 2,\n    parameter ADAPT_KN = 8, ADAPT_UP = 1, ADAPT_DOWN = 9, ADAPT_HOLD = 1\n)(", 1)
    a = "    wire chest_still = (scg_energy < SCG_THR);"
    assert a in p
    p = p.replace(a, """    // ---- ADAPTIVE still threshold (round-2 variant, B5) ----
    reg [19:0] floor_q4;                       // running low percentile of per-second chest energy, in codes x16
    wire pulse_present_w;                      // wrist pulse present (set below, after the band telemetry is declared)
    wire [19:0] e_q4 = {scg_energy, 4'b0};
    reg [19:0] floor_hist [0:15];               // floor of the last 16 s: the threshold uses the OLDEST value, so it cannot follow the floor down in the
    integer hi_;                                // few seconds before the wrist pulse loss is seen (found by the B5 diagnostics at 650 ug)
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin for (hi_ = 0; hi_ < 16; hi_ = hi_ + 1) floor_hist[hi_] <= 0; end
        else if (tick) begin floor_hist[0] <= floor_q4; for (hi_ = 1; hi_ < 16; hi_ = hi_ + 1) floor_hist[hi_] <= floor_hist[hi_-1]; end
    end
    wire [19:0] floor_old = ADAPT_HOLD ? floor_hist[15] : floor_q4;
    wire [31:0] k_floor = (floor_old * ADAPT_KN) >> 3;
    wire [15:0] still_thr = ((k_floor >> 4) > SCG_THR) ? (k_floor >> 4) : SCG_THR;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) floor_q4 <= 0;
        else if (tick && pulse_present_w && scg_energy != 16'hFFFF) begin
            if (e_q4 > floor_q4) floor_q4 <= floor_q4 + ADAPT_UP;
            else floor_q4 <= (floor_q4 > ADAPT_DOWN) ? floor_q4 - ADAPT_DOWN : 20'd0;
        end
    end
    wire chest_still = (scg_energy < still_thr);""", 1)
    a = "    wire band_fresh = (band_age < BAND_STALE_S);"
    assert a in p; p = p.replace(a, a + "\n    assign pulse_present_w = band_fresh && (band_ppg_pp != 16'hFFFF) && (band_ppg_pp >= PP_THR);", 1)
    open(f"{V}/pod_node_adaptive.sv", "w", encoding="utf-8").write("// GENERATED by py/b5_adaptive_sweep.py from rtl/pod_node.sv; do not edit by hand.\n" + p)
    t = open("rtl/sentry_device_top.sv", encoding="utf-8").read()
    t = t.replace("module sentry_device_top #(", "module sentry_device_top_adaptive #(", 1)
    a = "BLE_LOSS_PM = 0, GATE_EN = 1, ACC_NOISE_UG = 350\n)("
    assert a in t; t = t.replace(a, "BLE_LOSS_PM = 0, GATE_EN = 1, ACC_NOISE_UG = 350, ADAPT_KN = 8, ADAPT_UP = 1, ADAPT_DOWN = 9, ADAPT_HOLD = 1\n)(", 1)
    a = "    pod_node #(.CLK_HZ(CLK_HZ),"
    assert a in t; t = t.replace(a, "    pod_node_adaptive #(.ADAPT_KN(ADAPT_KN), .ADAPT_UP(ADAPT_UP), .ADAPT_DOWN(ADAPT_DOWN), .ADAPT_HOLD(ADAPT_HOLD), .CLK_HZ(CLK_HZ),", 1)
    open(f"{V}/sentry_device_top_adaptive.sv", "w", encoding="utf-8").write("// GENERATED from rtl/sentry_device_top.sv\n" + t)
    b = open("tb/tb_system_end_to_end.sv", encoding="utf-8").read()
    b = b.replace("module tb_system_end_to_end;", "module tb_system_end_to_end_adaptive;", 1)
    a = "    sentry_device_top #(.CLK_HZ(CLK_HZ),"
    assert a in b; b = b.replace(a, "    sentry_device_top_adaptive #(.ADAPT_KN(`KNV), .ADAPT_UP(`UPV), .ADAPT_DOWN(`DOWNV), .ADAPT_HOLD(`HOLDV), .CLK_HZ(CLK_HZ),", 1)
    open(f"{V}/tb_system_end_to_end_adaptive.sv", "w", encoding="utf-8").write("// GENERATED from tb/tb_system_end_to_end.sv (needs `KNV defined)\n" + b)
    print("generated", os.listdir(V))


def sh(cmd, check=True):
    r = subprocess.run(cmd, cwd=WORK, capture_output=True, text=True, shell=True)
    if check and r.returncode: sys.exit(f"FAILED: {cmd}\n{r.stdout[-1500:]}\n{r.stderr[-800:]}")
    return r.stdout


def build(noise, kn, up=1, down=9, hold=1):
    os.makedirs(WORK, exist_ok=True)
    lib = f"n{noise}k{kn}u{up}d{down}h{hold}"
    open(f"{WORK}/defs_{lib}.sv", "w").write(f"`define ACCN {noise}\n`define KNV {kn}\n`define UPV {up}\n`define DOWNV {down}\n`define HOLDV {hold}\n")
    srcs = [os.path.abspath(f"{WORK}/defs_{lib}.sv")] + [os.path.abspath(p) for p in sorted(
        [f"rtl/{f}" for f in os.listdir("rtl") if f.endswith(".sv")] + [f"model/{f}" for f in os.listdir("model") if f.endswith(".sv")]
        + [f"{V}/{f}" for f in os.listdir(V) if f.endswith(".sv")] + ["tb/tb_system_end_to_end.sv"])]
    sh(f"xvlog -sv -work {lib} " + " ".join(f'"{s}"' for s in srcs))
    for top in ("tb_system_end_to_end", "tb_system_end_to_end_adaptive"):
        sh(f"xelab {lib}.{top} -s {lib}_{top} --timescale 1ns/1ps -debug off")
    return lib


def run(lib, top, only):
    out = sh(f'xsim {lib}_{top} -runall -testplusarg "ONLY={only}"', check=False)
    m = re.search(r"=== (\d+) passed, (\d+) failed", out)
    fails = [l.strip() for l in out.splitlines() if "FAIL" in l]
    return (int(m[1]), int(m[2])) if m else (None, None), fails, out


if __name__ == "__main__":
    if sys.argv[1] == "gen": gen()
    elif sys.argv[1] == "sweep":
        rows = []
        specs = [(lambda t: t + ((1, 9, 1)[len(t) - 1:] if len(t) < 4 else ()))(tuple(int(v) for v in x.split(":"))) for x in sys.argv[2:]]
        for si, (kn, up, down, hold) in enumerate(specs):
            for noise in NOISES:
                lib = build(noise, kn, up, down, hold)
                for top, tag in (("tb_system_end_to_end", "baseline"), ("tb_system_end_to_end_adaptive", f"adaptive KN={kn} UP={up} DOWN={down} HOLD={hold}")):
                    if tag == "baseline" and si != 0: continue
                    for only in (1, 3, 5):
                        (p, f), fails, _ = run(lib, top, only)
                        rows.append(dict(variant=tag, acc_noise_ug=noise, scenario={1: "S1 normal rest", 3: "S3 watch loose (living)", 5: "S5 arrest"}[only], passed=p, failed=f,
                                         failing_checks="; ".join(x[:70] for x in fails)))
                        print(rows[-1], flush=True)
        with open(os.environ.get("B5_OUT", "results/b5_sweep.csv"), "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    elif sys.argv[1] == "full":
        kn, noise = int(sys.argv[2]), int(sys.argv[3]); up = int(sys.argv[4]) if len(sys.argv) > 4 else 1; down = int(sys.argv[5]) if len(sys.argv) > 5 else 9; hold = int(sys.argv[6]) if len(sys.argv) > 6 else 1; lib = build(noise, kn, up, down, hold); rows = []
        for top, tag in (("tb_system_end_to_end", "baseline"), ("tb_system_end_to_end_adaptive", f"adaptive KN={kn} UP={up} DOWN={down} HOLD={hold}")):
            (p, f), fails, out = run(lib, top, 0)
            rows.append(dict(variant=tag, acc_noise_ug=noise, passed=p, failed=f, failing_checks="; ".join(x[:70] for x in fails))); print(rows[-1], flush=True)
        with open(f"results/b5_full_{noise}.csv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
